/* integ.s - INTEG.COM: the storage-path INTEGRITY probe.
 *
 * WHY THIS EXISTS. The Policenauts intro stall was hard-disk data corruption: the
 * block adapter counted another hps_io slot's words (the CD's CD-DA stream) into the
 * hard disk's sector buffer. It took a day of tracing to see, because nothing in the
 * tree could say "the bytes DOS reads from this drive are not the bytes in the image".
 * INTEG says exactly that, in a minute, from inside the guest, on any drive DOS can
 * read: the hard disk, either floppy, the CD (through its MSCDEX drive letter), with
 * or without CD-DA playing.
 *
 *   INTEG V [man] [/PLAY] [/KEEP]  VERIFY: read every file the manifest lists, compare
 *                                  per-512-byte-block CRC32s and the whole-file CRC32,
 *                                  print each mismatch with its byte offset
 *   INTEG W d: [/K:n] [/PLAY]      WRITE/READ-BACK: two passes of a pseudo-random pattern
 *                                  (n KiB, default 256) over ONE scratch file
 *                                  d:\INTEGTMP.DAT, each read back and compared, then
 *                                  the file is deleted. Only that file is ever written.
 *   INTEG P                        start CD-DA play (first audio track to the lead-out)
 *                                  through MSCDEX and RETURN, audio continuing, so a
 *                                  run of V/W commands can follow it
 *   INTEG S                        stop CD-DA play
 *
 *   /PLAY  start CD-DA play before the command, stop it after (unless /KEEP)
 *   /D:x   substitute drive x for a manifest path that starts '*:' (one manifest for any CD letter)
 *
 * The manifest (default INTEG.MAN) is host-generated by integ_manifest.py from the SAME
 * image the core mounts, so every expected value comes from the image's own bytes:
 *
 *   INTEG1 512                      header; the block size is fixed at 512
 *   F <size hex8> <crc32 hex8> <path>   one file; path as DOS sees it, drive letter included
 *   B <crc32 hex8> <crc32 hex8> ...     the file's per-512-byte-block CRC32s, in order,
 *                                       any number per line; the LAST block is short
 *                                       when size % 512 != 0 and its CRC covers the
 *                                       bytes that exist
 *
 * OUTPUT. Plain text rows, every number HEX, built for grep and a diff:
 *
 *   INTEG BEGIN V1
 *   INTEG CMD V MAN=INTEG.MAN
 *   PLAY OK DRV=04 TRACK=01 START=00020000 SECTORS=0000A3D4        (only with /PLAY or P)
 *   FILE E:\GAME\DATA.BIN SIZE=00100000 CRC=1A2B3C4D WANT=1A2B3C4D BADBLK=00000000 OK
 *   BAD  E:\GAME\DATA.BIN OFF=00004200 BLK=00000021 GOT=... WANT=... DATA=xx xx ... (16 bytes)
 *   FILE ... FAIL
 *   INTEG END FAILS=0001
 *
 * The exit code is min(FAILS,255), so a .BAT can test it with IF ERRORLEVEL 1.
 *
 * SAFETY. Reads everything it names. The only write is the scratch file of mode W
 * (created, written, closed, read back and deleted; the row names it). /PLAY and P
 * issue MSCDEX play requests and nothing else to the drive. No port is touched.
 *
 * /PLAY IS UNVERIFIED ON HARDWARE. The MSCDEX request layout (INT 2Fh AX=1510h, play
 * audio = command 132, IOCTL input codes 10/11) is the documented MSCDEX 2.x one; it
 * has been executed against a model of MSCDEX in integ_selftest.py and has not yet run
 * on the core or the Xe10. If the NEC driver does not answer, the PLAY row says so
 * (NOMSCDEX / NOCD / NOAUDIO / FAIL) and the verify still runs, silent; then play audio
 * some other way (a CD player program, or the game itself).
 */

    .code16
    .intel_syntax noprefix

    .section .text
    .global _start

    /* fixed buffers above the image (a .COM owns the whole 64 KiB segment) */
    .equ BUF_IO,   0x4000           /* 4096: the file chunk                          */
    .equ BUF_EXP,  0x5000           /* 4096: the expected pattern (mode W)           */
    .equ BUF_MAN,  0x6000           /* 2048: the manifest read buffer                */
    .equ CRCTAB,   0x6800           /* 1024: CRC32 table                             */
    .equ PATHBUF,  0x6C00           /* 160:  current path                            */
    .equ MANNAME,  0x6CA0           /* 80:   manifest file name                      */
    .equ CHUNK,    4096
    .equ BLK,      512
    .equ MAXBAD,   8                /* BAD rows printed per file */

_start:
    cld
    mov     ax, cs
    mov     ds, ax
    mov     es, ax
    mov     sp, 0xFFFE
    mov     dword ptr [fails], 0
    mov     byte ptr [do_play], 0
    mov     byte ptr [vdrive], 0
    mov     byte ptr [do_keep], 0
    mov     word ptr [kib], 256
    mov     byte ptr [cmd], 0
    mov     byte ptr [playing], 0
    mov     word ptr [pushback], 0xFFFF
    call    build_crc
    /* INT 24h: answer every critical error with FAIL, so a drive that is 'Not ready' (the NEC CD
       driver says so for a data read while audio plays) becomes a READFAIL/OPENFAIL row instead of
       a blocked Abort/Retry/Fail prompt. The vector is the PSP's own and dies with the program. */
    mov     dx, offset crit24
    mov     ax, 0x2524
    int     0x21
    call    parse_tail
    cmp     byte ptr [cmd], 'P'
    jne     0f
    mov     byte ptr [do_play], 1
    mov     byte ptr [do_keep], 1
0:
    mov     si, offset s_begin
    call    puts
    cmp     byte ptr [cmd], 0
    je      usage
    mov     si, offset s_cmd
    call    puts
    mov     al, [cmd]
    call    putc
    cmp     byte ptr [cmd], 'V'
    jne     1f
    mov     si, offset s_man
    call    puts
    mov     si, offset MANNAME
    call    puts
1:  cmp     byte ptr [cmd], 'W'
    jne     2f
    mov     si, offset s_drv
    call    puts
    mov     al, [wdrive]
    call    putc
    mov     si, offset s_k
    call    puts
    mov     ax, [kib]
    call    put_hex16
2:   call    putnl

    cmp     byte ptr [cmd], 'S'
    je      do_stop_cmd
    cmp     byte ptr [do_play], 0
    je      3f
    call    cd_play
3:  cmp     byte ptr [cmd], 'P'
    je      finish
    cmp     byte ptr [cmd], 'V'
    jne     4f
    call    verify
    jmp     5f
4:  call    wmode
5:  cmp     byte ptr [do_play], 0
    je      finish
    cmp     byte ptr [do_keep], 0
    jne     finish
do_stop_cmd:
    call    cd_stop
finish:
    mov     si, offset s_end
    call    puts
    mov     eax, [fails]
    call    put_hex16
    call    putnl
    mov     eax, [fails]
    cmp     eax, 255
    jbe     6f
    mov     al, 255
6:  mov     ah, 0x4C
    int     0x21
    hlt

crit24:
    mov     al, 3                   /* fail the call */
    iret

usage:
    mov     si, offset s_usage
    call    puts
    mov     ax, 0x4C02
    int     0x21

/* ------------------------------------------------------------------ */
/* command tail                                                        */
/* ------------------------------------------------------------------ */
/* Tokens split on blanks, upper-cased. A token starting '/' is an option
 * (/PLAY, /KEEP, /K:n); the first other token is the command (first letter
 * V/W/P/S), the second is the manifest (V) or the drive (W). */
parse_tail:
    mov     byte ptr [wdrive], 0
    mov     si, offset DEFMAN
    mov     di, offset MANNAME
7:  lodsb
    stosb
    or      al, al
    jnz     7b
    xor     bx, bx                  /* positional count */
    mov     si, 0x81
    movzx   cx, byte ptr [0x80]
    add     cx, si                  /* end pointer */
pt_next:
    cmp     si, cx
    jae     pt_done
    mov     al, [si]
    cmp     al, ' '
    je      pt_skip
    cmp     al, 9
    je      pt_skip
    cmp     al, 13
    je      pt_done
    cmp     al, '/'
    je      pt_opt
    cmp     al, '-'
    je      pt_opt
    /* positional */
    cmp     bx, 0
    jne     pt_pos2
    call    upc
    mov     [cmd], al
    inc     bx
    jmp     pt_tokend
pt_pos2:
    cmp     byte ptr [cmd], 'W'
    jne     pt_manname
    call    upc
    mov     [wdrive], al
    jmp     pt_tokend
pt_manname:
    mov     di, offset MANNAME
8:  mov     al, [si]
    cmp     al, ' '
    jbe     9f
    call    upc
    mov     [di], al
    inc     di
    inc     si
    jmp     8b
9:  mov     byte ptr [di], 0
    jmp     pt_next
pt_opt:
    inc     si
    mov     al, [si]
    call    upc
    cmp     al, 'P'
    jne     pt_o2
    mov     byte ptr [do_play], 1
    jmp     pt_tokend
pt_o2:
    cmp     al, 'D'
    jne     pt_o3
    cmp     byte ptr [si+1], ':'
    jne     pt_tokend
    mov     al, [si+2]
    call    upc
    mov     [vdrive], al
    jmp     pt_tokend
pt_o3:
    cmp     al, 'K'
    jne     pt_tokend
    cmp     byte ptr [si+1], ':'
    jne     pt_keep
    add     si, 2
    xor     ax, ax
10: movzx   dx, byte ptr [si]
    sub     dl, '0'
    cmp     dl, 9
    ja      11f
    mov     di, 10
    push    dx
    mul     di
    pop     dx
    add     ax, dx
    inc     si
    jmp     10b
11: mov     [kib], ax
    jmp     pt_next
pt_keep:
    mov     byte ptr [do_keep], 1
pt_tokend:
    cmp     si, cx
    jae     pt_done
    mov     al, [si]
    cmp     al, ' '
    jbe     pt_next
    inc     si
    jmp     pt_tokend
pt_skip:
    inc     si
    jmp     pt_next
pt_done:
    cmp     byte ptr [cmd], 'W'
    jne     12f
    cmp     byte ptr [wdrive], 0
    jne     12f
    mov     byte ptr [cmd], 0
12: ret

upc:                                /* AL -> upper case */
    cmp     al, 'a'
    jb      13f
    cmp     al, 'z'
    ja      13f
    sub     al, 0x20
13: ret

/* ------------------------------------------------------------------ */
/* output                                                              */
/* ------------------------------------------------------------------ */
putc:
    push    ax
    push    dx
    mov     dl, al
    mov     ah, 2
    int     0x21
    pop     dx
    pop     ax
    ret
putnl:
    push    ax
    mov     al, 13
    call    putc
    mov     al, 10
    call    putc
    pop     ax
    ret
puts:                               /* DS:SI ASCIZ */
    push    ax
    push    si
14: lodsb
    or      al, al
    jz      15f
    call    putc
    jmp     14b
15: pop     si
    pop     ax
    ret
put_nib:
    and     al, 0x0F
    add     al, '0'
    cmp     al, '9'
    jbe     16f
    add     al, 7
16: jmp     putc
put_hex8:
    push    ax
    shr     al, 4
    call    put_nib
    pop     ax
    jmp     put_nib
put_hex16:
    push    ax
    mov     al, ah
    call    put_hex8
    pop     ax
    jmp     put_hex8
put_hex32:
    push    eax
    shr     eax, 16
    call    put_hex16
    pop     eax
    jmp     put_hex16
put_sp:
    push    ax
    mov     al, ' '
    call    putc
    pop     ax
    ret

/* ------------------------------------------------------------------ */
/* CRC32 (reflected, 0xEDB88320, init/xorout 0xFFFFFFFF = zlib's)      */
/* ------------------------------------------------------------------ */
build_crc:
    xor     ecx, ecx
    mov     di, offset CRCTAB
bc_l:
    mov     eax, ecx
    mov     dx, 8
bc_b:
    shr     eax, 1
    jnc     bc_n
    xor     eax, 0xEDB88320
bc_n:
    dec     dx
    jnz     bc_b
    mov     [di], eax
    add     di, 4
    inc     cx
    cmp     cx, 256
    jb      bc_l
    ret

/* crc_upd: DS:SI = data, CX = length, EDX = running crc (NOT final-xored). Updates EDX, SI. */
crc_upd:
    push    ebx
    push    eax
    or      cx, cx
    jz      cu_end
cu_l:
    movzx   ebx, byte ptr [si]
    inc     si
    xor     bl, dl
    shl     bx, 2
    shr     edx, 8
    xor     edx, [bx + CRCTAB]
    dec     cx
    jnz     cu_l
cu_end:
    pop     eax
    pop     ebx
    ret

/* ------------------------------------------------------------------ */
/* manifest stream                                                     */
/* ------------------------------------------------------------------ */
/* getc: AL = next manifest byte, CF=1 at end of file. */
getc:
    cmp     word ptr [pushback], 0xFFFF
    je      gc_buf
    mov     al, byte ptr [pushback]
    mov     word ptr [pushback], 0xFFFF
    clc
    ret
gc_buf:
    mov     bx, [mpos]
    cmp     bx, [mlen]
    jb      gc_have
    push    cx
    push    dx
    mov     bx, [man_h]
    mov     cx, 2048
    mov     dx, offset BUF_MAN
    mov     ah, 0x3F
    int     0x21
    pop     dx
    pop     cx
    jc      gc_eof
    mov     [mlen], ax
    mov     word ptr [mpos], 0
    or      ax, ax
    jz      gc_eof
    mov     bx, 0
gc_have:
    mov     al, [bx + BUF_MAN]
    inc     bx
    mov     [mpos], bx
    clc
    ret
gc_eof:
    stc
    ret
ungetc:                             /* AL */
    mov     byte ptr [pushback], al
    mov     byte ptr [pushback + 1], 0
    ret

/* hexchar: AL char -> AL value, CF=1 if not a hex digit */
hexchar:
    cmp     al, '0'
    jb      hx_bad
    cmp     al, '9'
    jbe     hx_dig
    call    upc
    cmp     al, 'A'
    jb      hx_bad
    cmp     al, 'F'
    ja      hx_bad
    sub     al, 'A' - 10
    clc
    ret
hx_dig:
    sub     al, '0'
    clc
    ret
hx_bad:
    stc
    ret

/* hex8 starting with the digit in AL already read; reads 7 more. EAX = value, CF=1 if malformed. */
hex8:
    push    ecx
    push    edx
    xor     edx, edx
    mov     cx, 8
h8_l:
    call    hexchar
    jc      h8_bad
    shl     edx, 4
    movzx   eax, al
    or      edx, eax
    dec     cx
    jz      h8_ok
    call    getc
    jc      h8_bad
    jmp     h8_l
h8_ok:
    mov     eax, edx
    pop     edx
    pop     ecx
    clc
    ret
h8_bad:
    pop     edx
    pop     ecx
    stc
    ret

/* skip_sp: skip blanks (not newlines); returns AL = the first other char, CF=1 at EOF */
skip_sp:
    call    getc
    jc      ss_ret
    cmp     al, ' '
    je      skip_sp
    cmp     al, 9
    je      skip_sp
    clc
ss_ret:
    ret
/* skip_ws: skip blanks AND newlines */
skip_ws:
    call    getc
    jc      sw_ret
    cmp     al, ' '
    je      skip_ws
    cmp     al, 9
    je      skip_ws
    cmp     al, 13
    je      skip_ws
    cmp     al, 10
    je      skip_ws
    clc
sw_ret:
    ret
skip_eol:
    call    getc
    jc      se_ret
    cmp     al, 10
    jne     skip_eol
    clc
se_ret:
    ret

/* next_blk: EAX = the next block CRC of the current file; CF=1 if the file has no more.
 * A line's first char is a marker: 'B' continues the list, anything else ends it (pushed back). */
next_blk:
    cmp     byte ptr [at_bol], 0
    je      nb_tok
nb_marker:
    call    skip_ws
    jc      nb_end
    cmp     al, 'B'
    jne     nb_stop
    mov     byte ptr [at_bol], 0
nb_tok:
    call    skip_sp
    jc      nb_end
    cmp     al, 13
    je      nb_tok
    cmp     al, 10
    jne     nb_hex
    mov     byte ptr [at_bol], 1
    jmp     nb_marker
nb_hex:
    call    hex8
    jc      nb_bad
    clc
    ret
nb_stop:
    call    ungetc
    mov     byte ptr [at_bol], 1
nb_end:
    stc
    ret
nb_bad:
    mov     byte ptr [man_bad], 1
    stc
    ret

/* ------------------------------------------------------------------ */
/* mode V                                                              */
/* ------------------------------------------------------------------ */
verify:
    mov     dx, offset MANNAME
    mov     ax, 0x3D00
    int     0x21
    jnc     v_opened
    mov     [dos_ax], ax
    mov     si, offset s_manfail
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    ret
v_opened:
    mov     [man_h], ax
    mov     word ptr [mpos], 0
    mov     word ptr [mlen], 0
    mov     byte ptr [man_bad], 0
    mov     byte ptr [at_bol], 1
    mov     dword ptr [nfiles], 0
v_line:
    call    skip_ws
    jc      v_eof
    cmp     al, 'F'
    je      v_file
    call    skip_eol_from           /* '#', the INTEG1 header, a stray B line */
    jmp     v_line
v_file:
    call    do_file
    cmp     byte ptr [man_bad], 0
    jne     v_malformed
    jmp     v_line
v_malformed:
    mov     si, offset s_malformed
    call    puts
    call    putnl
    inc     dword ptr [fails]
v_eof:
    mov     bx, [man_h]
    mov     ah, 0x3E
    int     0x21
    cmp     dword ptr [nfiles], 0
    jne     v_ret
    mov     si, offset s_nofiles
    call    puts
    call    putnl
    inc     dword ptr [fails]
v_ret:
    ret
skip_eol_from:                      /* the line's first char is already consumed */
    cmp     al, 10
    je      v_sef
    call    skip_eol
v_sef:
    mov     byte ptr [at_bol], 1
    ret

/* do_file: after the 'F' marker. */
do_file:
    inc     dword ptr [nfiles]
    call    skip_sp
    jc      df_bad
    call    hex8
    jc      df_bad
    mov     [f_size], eax
    call    skip_sp
    jc      df_bad
    call    hex8
    jc      df_bad
    mov     [f_want], eax
    call    skip_sp
    jc      df_bad
    mov     di, offset PATHBUF
df_p:
    cmp     al, 13
    je      df_pe
    cmp     al, 10
    je      df_pe
    cmp     al, ' '
    jb      df_pe
    mov     [di], al
    inc     di
    call    getc
    jc      df_pe
    jmp     df_p
df_pe:
    mov     byte ptr [di], 0
    cmp     byte ptr [PATHBUF], '*'      /* '*:\x' = the drive given by /D:x (a manifest made for any CD drive letter) */
    jne     df_nostar
    mov     al, [vdrive]
    or      al, al
    jz      df_nostar
    mov     [PATHBUF], al
df_nostar:
    cmp     al, 10
    je      df_eol
    call    skip_eol
df_eol:
    mov     byte ptr [at_bol], 1
    /* open */
    mov     dx, offset PATHBUF
    mov     ax, 0x3D00
    int     0x21
    jnc     df_open
    mov     [dos_ax], ax
    mov     si, offset s_file
    call    puts
    mov     si, offset PATHBUF
    call    puts
    mov     si, offset s_openfail
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    call    drain_blks
    ret
df_open:
    mov     [f_h], ax
    mov     dword ptr [f_pos], 0
    mov     dword ptr [f_blk], 0
    mov     dword ptr [f_bad], 0
    mov     dword ptr [f_crc], 0xFFFFFFFF
    mov     byte ptr [f_short], 0
    mov     byte ptr [f_mshort], 0
df_rd:
    mov     eax, [f_size]
    sub     eax, [f_pos]
    jbe     df_done
    mov     cx, CHUNK
    cmp     eax, CHUNK
    jae     df_cx
    mov     cx, ax
df_cx:
    mov     [want_cx], cx
    mov     word ptr [have_cx], 0
df_fill:
    mov     bx, [f_h]
    mov     cx, [want_cx]
    sub     cx, [have_cx]
    mov     dx, offset BUF_IO
    add     dx, [have_cx]
    mov     ah, 0x3F
    int     0x21
    jnc     df_got
    mov     [dos_ax], ax
    mov     si, offset s_file
    call    puts
    mov     si, offset PATHBUF
    call    puts
    mov     si, offset s_readfail
    call    puts
    mov     eax, [f_pos]
    call    put_hex32
    mov     si, offset s_ax
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    mov     byte ptr [f_short], 2
    jmp     df_done
df_got:
    add     [have_cx], ax           /* DOS may return less than asked (track-bounded reads) */
    or      ax, ax
    jnz     df_more
    cmp     word ptr [have_cx], 0
    jne     df_have
    mov     byte ptr [f_short], 1
    jmp     df_done
df_more:
    mov     cx, [have_cx]
    cmp     cx, [want_cx]
    jb      df_fill
df_have:
    movzx   eax, word ptr [have_cx]
    mov     [chunk_rem], eax
    mov     si, offset BUF_IO
df_blk:
    cmp     dword ptr [chunk_rem], 0
    je      df_chunk_end
    mov     cx, BLK
    cmp     dword ptr [chunk_rem], BLK
    jae     df_bl
    mov     cx, word ptr [chunk_rem]
df_bl:
    mov     [blk_len], cx
    mov     [blk_si], si
    /* whole-file crc */
    mov     edx, [f_crc]
    call    crc_upd
    mov     [f_crc], edx
    /* this block's crc */
    mov     si, [blk_si]
    mov     cx, [blk_len]
    mov     edx, 0xFFFFFFFF
    call    crc_upd
    not     edx
    mov     [blk_got], edx
    call    next_blk
    jc      df_nomblk
    cmp     eax, [blk_got]
    je      df_blk_ok
    mov     [blk_want], eax
    inc     dword ptr [f_bad]
    cmp     dword ptr [f_bad], MAXBAD
    ja      df_blk_ok
    call    bad_row
df_blk_ok:
    jmp     df_blk_next
df_nomblk:
    mov     byte ptr [f_mshort], 1
df_blk_next:
    inc     dword ptr [f_blk]
    movzx   eax, word ptr [blk_len]
    add     [f_pos], eax
    sub     [chunk_rem], eax
    mov     si, [blk_si]
    add     si, [blk_len]
    jmp     df_blk
df_chunk_end:
    jmp     df_rd
df_done:
    mov     bx, [f_h]
    mov     ah, 0x3E
    int     0x21
    call    drain_blks
    mov     eax, [f_crc]
    not     eax
    mov     [f_crc], eax
    /* verdict */
    mov     byte ptr [f_ok], 1
    cmp     byte ptr [f_short], 0
    je      df_v1
    mov     byte ptr [f_ok], 0
df_v1:
    cmp     dword ptr [f_bad], 0
    je      df_v2
    mov     byte ptr [f_ok], 0
df_v2:
    mov     eax, [f_crc]
    cmp     eax, [f_want]
    je      df_v3
    mov     byte ptr [f_ok], 0
df_v3:
    cmp     byte ptr [f_mshort], 0
    je      df_v4
    mov     byte ptr [f_ok], 0
df_v4:
    mov     si, offset s_file
    call    puts
    mov     si, offset PATHBUF
    call    puts
    mov     si, offset s_size
    call    puts
    mov     eax, [f_pos]
    call    put_hex32
    mov     si, offset s_crc
    call    puts
    mov     eax, [f_crc]
    call    put_hex32
    mov     si, offset s_want
    call    puts
    mov     eax, [f_want]
    call    put_hex32
    mov     si, offset s_badblk
    call    puts
    mov     eax, [f_bad]
    call    put_hex32
    cmp     byte ptr [f_short], 0
    je      df_s1
    mov     si, offset s_shortf
    call    puts
    mov     al, [f_short]
    call    put_hex8
df_s1:
    cmp     byte ptr [f_mshort], 0
    je      df_s2
    mov     si, offset s_mshort
    call    puts
df_s2:
    cmp     byte ptr [f_ok], 0
    jne     df_ok
    mov     si, offset s_fail
    call    puts
    call    putnl
    inc     dword ptr [fails]
    ret
df_ok:
    mov     si, offset s_ok
    call    puts
    call    putnl
    ret
df_bad:
    mov     byte ptr [man_bad], 1
    ret

/* the manifest's block list of a file that was not (fully) read must still be consumed */
drain_blks:
    call    next_blk
    jnc     drain_blks
    ret

/* BAD row: offset, block, got, want and the block's first 16 bytes. f_blk/f_pos/blk_* set. */
bad_row:
    push    ebx
    push    si
    mov     si, offset s_bad
    call    puts
    mov     si, offset PATHBUF
    call    puts
    mov     si, offset s_off
    call    puts
    mov     eax, [f_pos]
    call    put_hex32
    mov     si, offset s_blkn
    call    puts
    mov     eax, [f_blk]
    call    put_hex32
    mov     si, offset s_got
    call    puts
    mov     eax, [blk_got]
    call    put_hex32
    mov     si, offset s_want
    call    puts
    mov     eax, [blk_want]
    call    put_hex32
    mov     si, offset s_data
    call    puts
    mov     si, [blk_si]
    mov     cx, 16
    cmp     cx, [blk_len]
    jbe     br_l
    mov     cx, [blk_len]
br_l:
    or      cx, cx
    jz      br_e
    lodsb
    call    put_hex8
    call    put_sp
    dec     cx
    jmp     br_l
br_e:
    call    putnl
    pop     si
    pop     ebx
    ret

/* ------------------------------------------------------------------ */
/* mode W                                                              */
/* ------------------------------------------------------------------ */
/* gen_block: ES:DI <- 512 bytes of the pattern for block EDX (global block index), pass [pass]. */
gen_block:
    push    ecx
    push    eax
    mov     eax, edx
    inc     eax
    imul    eax, eax, 0x9E3779B1
    movzx   ecx, byte ptr [pass]
    imul    ecx, ecx, 0x85EBCA6B
    xor     eax, ecx
    xor     eax, 0x1234567
    or      eax, 1
    mov     cx, 128
gb_l:
    mov     ebx, eax
    shl     ebx, 13
    xor     eax, ebx
    mov     ebx, eax
    shr     ebx, 17
    xor     eax, ebx
    mov     ebx, eax
    shl     ebx, 5
    xor     eax, ebx
    stosd
    dec     cx
    jnz     gb_l
    pop     eax
    pop     ecx
    ret

wmode:
    /* the path: X:\INTEGTMP.DAT */
    mov     al, [wdrive]
    mov     [wpath], al
    /* free space: AH=36h, DL = drive (1 = A) */
    mov     dl, [wdrive]
    sub     dl, 'A' - 1
    mov     ah, 0x36
    int     0x21
    cmp     ax, 0xFFFF
    jne     w_space
    mov     si, offset s_wnodrv
    call    puts
    call    putnl
    inc     dword ptr [fails]
    ret
w_space:
    movzx   eax, ax                 /* sectors per cluster */
    movzx   ebx, bx                 /* free clusters */
    movzx   ecx, cx                 /* bytes per sector */
    imul    eax, ebx
    imul    eax, ecx
    shr     eax, 10                 /* free KiB (a FAT volume is under 4 GiB) */
    sub     eax, 16                 /* directory and FAT growth */
    jbe     w_nospace
    movzx   ecx, word ptr [kib]
    cmp     ecx, eax
    jbe     w_sz
    mov     ecx, eax
w_sz:
    and     ecx, 0xFFFFFFFC         /* whole 4 KiB chunks */
    mov     [w_kib], ecx
    jnz     w_run
w_nospace:
    mov     si, offset s_wnospace
    call    puts
    call    putnl
    inc     dword ptr [fails]
    ret
w_run:
    mov     byte ptr [pass], 0
w_pass:
    call    w_write
    jc      w_ret
    call    w_read
    inc     byte ptr [pass]
    cmp     byte ptr [pass], 2
    jb      w_pass
w_ret:
    call    w_del                   /* whatever happened, the scratch file does not stay */
    ret

/* write [w_kib] KiB of pattern pass [pass] */
w_write:
    mov     dx, offset wpath
    xor     cx, cx
    mov     ah, 0x3C
    int     0x21
    jnc     ww_open
    mov     [dos_ax], ax
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_create
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    stc
    ret
ww_open:
    mov     [f_h], ax
    mov     dword ptr [w_blk], 0
    mov     eax, [w_kib]
    shr     eax, 2                  /* 4 KiB chunks */
    mov     [w_chunks], eax
ww_chunk:
    cmp     dword ptr [w_chunks], 0
    je      ww_close
    mov     di, offset BUF_IO
    mov     cx, 8
ww_g:
    mov     edx, [w_blk]
    call    gen_block
    inc     dword ptr [w_blk]
    dec     cx
    jnz     ww_g
    mov     bx, [f_h]
    mov     cx, CHUNK
    mov     dx, offset BUF_IO
    mov     ah, 0x40
    int     0x21
    jc      ww_err
    cmp     ax, CHUNK
    jne     ww_full
    dec     dword ptr [w_chunks]
    jmp     ww_chunk
ww_full:
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_wfull
    call    puts
    call    putnl
    inc     dword ptr [fails]
    mov     bx, [f_h]
    mov     ah, 0x3E
    int     0x21
    stc
    ret
ww_err:
    mov     [dos_ax], ax
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_write
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    mov     bx, [f_h]
    mov     ah, 0x3E
    int     0x21
    stc
    ret
ww_close:
    mov     bx, [f_h]
    mov     ah, 0x3E
    int     0x21
    mov     ah, 0x0D                /* disk reset: flush DOS's buffers */
    int     0x21
    clc
    ret

w_del:
    mov     dx, offset wpath
    mov     ah, 0x41
    int     0x21
    ret

/* read the file back and compare with the pattern */
w_read:
    mov     dx, offset wpath
    mov     ax, 0x3D00
    int     0x21
    jnc     wr_open
    mov     [dos_ax], ax
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_reopen
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    ret
wr_open:
    mov     [f_h], ax
    mov     dword ptr [w_blk], 0
    mov     dword ptr [f_bad], 0
    mov     eax, [w_kib]
    shr     eax, 2
    mov     [w_chunks], eax
wr_chunk:
    cmp     dword ptr [w_chunks], 0
    je      wr_end
    mov     bx, [f_h]
    mov     cx, CHUNK
    mov     dx, offset BUF_IO
    mov     ah, 0x3F
    int     0x21
    jc      wr_err
    cmp     ax, CHUNK
    jne     wr_short
    mov     di, offset BUF_EXP
    mov     cx, 8
wr_g:
    mov     edx, [w_blk]
    add     edx, 8
    movzx   eax, cx
    sub     edx, eax                /* block index of the k-th block in the chunk */
    call    gen_block
    dec     cx
    jnz     wr_g
    /* compare block by block so each BAD row names its 512-byte block */
    xor     bx, bx                  /* block within chunk */
wr_cmp:
    mov     si, offset BUF_IO
    mov     ax, bx
    shl     ax, 9
    add     si, ax
    mov     di, offset BUF_EXP
    add     di, ax
    mov     cx, 128
    repe cmpsd
    je      wr_blk_ok
    inc     dword ptr [f_bad]
    cmp     dword ptr [f_bad], MAXBAD
    ja      wr_blk_ok
    /* si/di are one dword past the first difference */
    sub     si, 4
    sub     di, 4
    mov     eax, [si]
    mov     [blk_got], eax
    mov     eax, [di]
    mov     [blk_want], eax
    movzx   eax, si
    sub     eax, offset BUF_IO       /* byte offset inside this 4 KiB chunk */
    mov     [w_si], eax
    movzx   eax, bx
    add     eax, [w_blk]
    mov     [w_cb], eax             /* block number in the file */
    mov     [wr_bx], bx
    mov     si, offset s_bad
    call    puts
    mov     si, offset wpath
    call    puts
    mov     si, offset s_off
    call    puts
    mov     eax, [w_blk]
    shl     eax, 9
    add     eax, [w_si]
    call    put_hex32
    mov     si, offset s_blkn
    call    puts
    mov     eax, [w_cb]
    call    put_hex32
    mov     si, offset s_pass
    call    puts
    mov     al, [pass]
    call    put_hex8
    mov     si, offset s_got
    call    puts
    mov     eax, [blk_got]
    call    put_hex32
    mov     si, offset s_want
    call    puts
    mov     eax, [blk_want]
    call    put_hex32
    call    putnl
    mov     bx, [wr_bx]
wr_blk_ok:
    inc     bx
    cmp     bx, 8
    jb      wr_cmp
    add     dword ptr [w_blk], 8
    dec     dword ptr [w_chunks]
    jmp     wr_chunk
wr_short:
    mov     [dos_ax], ax
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_wshort
    call    puts
    mov     eax, [w_blk]
    shl     eax, 9
    call    put_hex32
    call    putnl
    inc     dword ptr [fails]
    jmp     wr_close
wr_err:
    mov     [dos_ax], ax
    mov     si, offset s_wfail
    call    puts
    mov     si, offset s_readfail
    call    puts
    mov     ax, [dos_ax]
    call    put_hex16
    call    putnl
    inc     dword ptr [fails]
    jmp     wr_close
wr_end:
    mov     si, offset s_wrow
    call    puts
    mov     si, offset wpath
    call    puts
    mov     si, offset s_pass
    call    puts
    mov     al, [pass]
    call    put_hex8
    mov     si, offset s_kib
    call    puts
    mov     eax, [w_kib]
    call    put_hex16
    mov     si, offset s_badblk
    call    puts
    mov     eax, [f_bad]
    call    put_hex32
    cmp     dword ptr [f_bad], 0
    jne     wr_f
    mov     si, offset s_ok
    call    puts
    call    putnl
    jmp     wr_close
wr_f:
    mov     si, offset s_fail
    call    puts
    call    putnl
    inc     dword ptr [fails]
wr_close:
    mov     bx, [f_h]
    mov     ah, 0x3E
    int     0x21
    ret                             /* the file stays for pass 1 to overwrite; w_ret deletes it */

/* ------------------------------------------------------------------ */
/* CD-DA through MSCDEX (INT 2Fh AX=1510h)                             */
/* ------------------------------------------------------------------ */
/* request buffer layout (all at reqbuf): 13-byte header, then the command's own fields. */
mscdex_call:                        /* CX = drive; reqbuf filled; CF = failure or error status */
    mov     ax, cs
    mov     es, ax
    mov     bx, offset reqbuf
    mov     ax, 0x1510
    int     0x2F
    mov     ax, cs
    mov     es, ax
    mov     ax, [reqbuf + 3]
    test    ax, 0x8000
    jnz     mc_err
    clc
    ret
mc_err:
    stc
    ret

req_clear:                          /* zero 40 bytes of reqbuf */
    push    di
    push    cx
    push    ax
    mov     di, offset reqbuf
    mov     cx, 20
    xor     ax, ax
    rep     stosw
    pop     ax
    pop     cx
    pop     di
    ret

cd_play:
    mov     si, offset s_play
    call    puts
    mov     ax, 0x1500
    xor     bx, bx
    int     0x2F
    or      bx, bx
    jnz     cp_have
    mov     si, offset s_nomscdex
    call    puts
    call    putnl
    ret
cp_have:
    mov     [cd_drv], cx
    /* IOCTL input, code 10: audio disk info */
    call    req_clear
    mov     byte ptr [reqbuf], 26
    mov     byte ptr [reqbuf + 2], 3
    mov     word ptr [reqbuf + 14], offset ctlbuf
    mov     word ptr [reqbuf + 16], cs
    mov     word ptr [reqbuf + 18], 7
    mov     byte ptr [ctlbuf], 10
    mov     cx, [cd_drv]
    call    mscdex_call
    jc      cp_noaudio
    movzx   ax, byte ptr [ctlbuf + 1]       /* lowest track */
    mov     [cd_lo], al
    mov     al, [ctlbuf + 2]
    mov     [cd_hi], al
    mov     eax, [ctlbuf + 3]               /* lead-out: frame, sec, min, 0 */
    mov     [cd_lead], eax
    /* find the first audio track */
    movzx   ax, byte ptr [cd_lo]
    mov     [cd_trk], al
cp_trk:
    mov     al, [cd_trk]
    cmp     al, [cd_hi]
    ja      cp_noaudio
    call    req_clear
    mov     byte ptr [reqbuf], 26
    mov     byte ptr [reqbuf + 2], 3
    mov     word ptr [reqbuf + 14], offset ctlbuf
    mov     word ptr [reqbuf + 16], cs
    mov     word ptr [reqbuf + 18], 7
    mov     byte ptr [ctlbuf], 11
    mov     al, [cd_trk]
    mov     [ctlbuf + 1], al
    mov     cx, [cd_drv]
    call    mscdex_call
    jc      cp_noaudio
    test    byte ptr [ctlbuf + 6], 0x40     /* control bit 6 = DATA track */
    jz      cp_audio
    inc     byte ptr [cd_trk]
    jmp     cp_trk
cp_audio:
    mov     eax, [ctlbuf + 2]               /* start: frame, sec, min, 0 */
    mov     [cd_start], eax
    /* sectors = lead-out - start, both min*4500 + sec*75 + frame */
    mov     eax, [cd_lead]
    call    rb2frames
    mov     [cd_len], eax
    mov     eax, [cd_start]
    call    rb2frames
    sub     [cd_len], eax
    /* PLAY AUDIO (132): header 13, addressing mode 1 = Red Book, start, sectors */
    call    req_clear
    mov     byte ptr [reqbuf], 22
    mov     byte ptr [reqbuf + 2], 132
    mov     byte ptr [reqbuf + 13], 1
    mov     eax, [cd_start]
    mov     [reqbuf + 14], eax
    mov     eax, [cd_len]
    mov     [reqbuf + 18], eax
    mov     cx, [cd_drv]
    call    mscdex_call
    jc      cp_fail
    mov     byte ptr [playing], 1
    mov     si, offset s_playok
    call    puts
    mov     ax, [cd_drv]
    call    put_hex8
    mov     si, offset s_track
    call    puts
    mov     al, [cd_trk]
    call    put_hex8
    mov     si, offset s_start
    call    puts
    mov     eax, [cd_start]
    call    put_hex32
    mov     si, offset s_sectors
    call    puts
    mov     eax, [cd_len]
    call    put_hex32
    call    putnl
    ret
cp_noaudio:
    mov     si, offset s_noaudio
    call    puts
    call    putnl
    ret
cp_fail:
    mov     si, offset s_playfail
    call    puts
    mov     ax, [reqbuf + 3]
    call    put_hex16
    call    putnl
    ret

rb2frames:                          /* EAX = frame|sec<<8|min<<16 -> EAX = total frames */
    push    ebx
    push    ecx
    movzx   ebx, al                 /* frame */
    movzx   ecx, ah                 /* sec */
    imul    ecx, ecx, 75
    add     ebx, ecx
    shr     eax, 16
    movzx   eax, al                 /* min */
    imul    eax, eax, 4500
    add     eax, ebx
    pop     ecx
    pop     ebx
    ret

cd_stop:
    cmp     byte ptr [playing], 0
    jne     cs_do
    cmp     byte ptr [cmd], 'S'
    jne     cs_ret
    /* an S command stops whatever the drive is playing */
    mov     ax, 0x1500
    xor     bx, bx
    int     0x2F
    or      bx, bx
    jz      cs_ret
    mov     [cd_drv], cx
cs_do:
    call    req_clear
    mov     byte ptr [reqbuf], 13
    mov     byte ptr [reqbuf + 2], 133
    mov     cx, [cd_drv]
    call    mscdex_call
    mov     byte ptr [playing], 0
    mov     si, offset s_stop
    call    puts
    call    putnl
cs_ret:
    ret

