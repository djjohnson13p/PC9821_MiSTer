#!/usr/bin/env python3
"""Generate FIGD bench inputs and expected pixels from unmodified Xe10 captures.

No drawing algorithm lives here: changed words and cursor values are copied from
the hardware CSV, including INFO/OBS rows (observations, not suite assertions).
ERROR/FAIL rows and truncated change lists are rejected, not treated as an oracle.
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/probes/gdc-conformance/xe10-2.5MHz'
OUTPUT = ROOT / 'tests/pc9821/gdc_figd_vectors.svh'


def rows(name):
    return csv.DictReader(s for s in (SOURCE / name).read_text().splitlines()
                          if not s.startswith('#'))


def render():
    vectors, words, names = [], [], []
    for filename in ('GDCDRAW.CSV', 'GDCROP.CSV'):
        for row in rows(filename):
            if filename == 'GDCDRAW.CSV':
                if row['class'] not in ('DOT', 'DOT_DIR', 'LINE_CANON', 'PATTERN'):
                    continue
                p1 = int(row['p1'], 16)
                params = [int(row[k]) & 0xffff for k in ('dc', 'd', 'd2', 'd1', 'dm')]
                ead, dad = int(row['start_ead'], 16), int(row['start_dad'])
                pattern = 0xA53C if row['class'] == 'PATTERN' else 0xFFFF
                rop, old = 3, 0
            else:
                if row['class'] != 'FIGD_ROP':
                    continue
                p1, params, ead = 0, [0] * 5, 0x9000
                dad, pattern = int(row['dad']), int(row['pattern'], 16)
                rop, old = int(row['rop']) & 3, int(row['old'], 16)
            if row['outcome'] not in ('PASS', 'OBS'):
                raise ValueError('non-oracle row selected: ' + row['case'])
            count, change = row['changes'].split('/', 1)
            changes = []
            if change:
                for entry in change.split('|'):
                    m = re.fullmatch(r'R:([0-9A-F]{4}):([0-9A-F]{4})>([0-9A-F]{4})', entry)
                    if not m:
                        raise ValueError('incomplete change list: ' + row['case'])
                    off, before, after = (int(v, 16) for v in m.groups())
                    if before != old:
                        raise ValueError('unexpected baseline: ' + row['case'])
                    changes.append((off, after))
            if len(changes) != int(count):
                raise ValueError('truncated change list: ' + row['case'])
            curd = row['curd'].split('/')
            end_ead, end_mask = int(curd[1], 16), int(curd[2][1:], 16)
            fields = [(p1, 8), *[(v, 16) for v in params], (ead, 18), (dad, 4),
                      (pattern, 16), (rop, 2), (old, 16), (end_ead, 18),
                      (end_mask, 16), (len(words), 16), (len(changes), 6)]
            value = 0
            for data, width in fields:
                if data >= (1 << width):
                    raise ValueError('field overflow: ' + row['case'])
                value = (value << width) | data
            vectors.append(f"    200'h{value:050X}")
            words.extend((off << 16) | value for off, value in changes)
            names.append(f"{filename}:{row['case']} [{row['expect']}/{row['outcome']}]")
    result = ['// Generated by tools/gen_gdc_figd_vectors.py; do not edit.',
              '// Oracle: unmodified real Xe10 CSV rows, not a model of the DUT.',
              f'localparam integer FIGD_CASES = {len(vectors)};',
              f"localparam logic [199:0] FIGD_VECTORS [0:FIGD_CASES-1] = '{{"]
    result += [vector + (',' if i + 1 < len(vectors) else '') + ' // ' + names[i]
               for i, vector in enumerate(vectors)]
    result += ['};', f'localparam integer FIGD_WORDS = {len(words)};',
               "localparam logic [29:0] FIGD_PIXELS [0:FIGD_WORDS-1] = '{"]
    result += [f"    30'h{value:08X}" + (',' if i + 1 < len(words) else '')
               for i, value in enumerate(words)]
    return '\n'.join(result + ['};', ''])


if __name__ == '__main__':
    generated = render()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            sys.exit('FAIL: regenerate tests/pc9821/gdc_figd_vectors.svh')
        print('GDC FIGD capture vectors: PASS')
    else:
        OUTPUT.write_text(generated, newline='\n')
        print(OUTPUT)
