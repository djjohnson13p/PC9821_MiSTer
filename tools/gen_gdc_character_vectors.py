#!/usr/bin/env python3
"""Capture-derived GCHRD oracle; commands follow NEC Design Manual v3 4.24.13-14.

No pixel algorithm. Nine rows with unspecified glyph bytes remain explicitly
unreplayed; do not reverse-engineer their inputs from their expected output.
"""
import csv,pathlib,re,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE=ROOT/'docs/probes/gdc-conformance/xe10-2.5MHz/GDCGCHR.CSV'
OUTPUT=ROOT/'tests/pc9821/gdc_character_vectors.svh'
def render():
 rows=list(csv.DictReader(l for l in SOURCE.read_text().splitlines() if not l.startswith('#')))
 if len(rows)!=554:raise ValueError('Expected554 data rows; old README555 is not the footer count')
 vectors=[];words=[];unknown=[];seen=set()
 for row in rows:
  name=row['case'];cls=row['class'];params=row['params'];pram=[0]*8;zoom=0;rop=3;start=8;length=8;dc=7;d=8;direction=0
  if name in seen:raise ValueError('Duplicate case '+name)
  seen.add(name)
  if row['outcome'] not in ('OBS','PASS') or '...' in row['changes']:raise ValueError('Non-oracle/truncated '+name)
  count,entries=row['changes'].split('/',1);changes=[]
  for entry in entries.split('|') if entries else []:
   m=re.fullmatch(r'R:([0-9A-F]{4}):([0-9A-F]{4})>([0-9A-F]{4})',entry)
   if not m:raise ValueError('Bad change '+name)
   off,before,after=[int(v,16) for v in m.groups()]
   if off>=16384:raise ValueError('Plane offset '+name)
   changes.append((off,before,after))
  if len(changes)!=int(count):raise ValueError('Incomplete changes '+name)
  if cls=='GCHR_ONEHOT':
   m=re.fullmatch(r'OH_B(\d+)_b(\d+)_D(\d+)',name)
   if not m:raise ValueError(name)
   byte,bit,direction=map(int,m.groups());pram[byte-8]=1<<bit
   if params!=f'pram={byte}.{bit};dir={direction};dc=7;d=8;zoom=1;rop=set':raise ValueError('Unknown input '+name)
  elif cls=='GCHR_AREA':
   m=re.fullmatch(r'solid;dir=0;w=(\d+);h=(\d+);dc=(\d+);d=(\d+)',params)
   if not m:raise ValueError(name)
   width,height,dc,d=map(int,m.groups())
   if dc!=width-1 or d!=height:raise ValueError(name)
   pram=[255]*8
  elif cls=='GCHR_ZOOM':
   m=re.fullmatch(r'onehot-pram15.0;dir=0;zoomreg=(\d+);factor=(\d+)',params)
   if not m:raise ValueError(name)
   zoom,factor=map(int,m.groups())
   if factor!=zoom+1:raise ValueError(name)
   pram[7]=1
  elif cls=='GCHR_REPLACE' and name=='REPLACE_ZERO':
   if params!='pattern=all-zero;dest=FFFF;8x8':raise ValueError(name)
   rop=0
  elif cls=='GCHR_PRAM_ADDR':
   m=re.fullmatch(r'opcode=([0-9A-F]{2});one-byte=01;8x8',params)
   if not m:raise ValueError(name)
   start=int(m[1],16)&15;length=1;pram[start-8]=1
  elif cls=='GCHR_SLANT' or (cls=='GCHR_REPLACE' and name=='REPLACE_MIXED'):
   unknown.append(name);continue
  else:raise ValueError('Unsupported capture class '+cls)
  curd=row['curd'].split('/');ead=int(curd[1],16);mask=int(curd[2][1:],16)
  fields=[(0x10|direction,8),(dc,16),(d,16),(zoom,4),(sum(v<<(i*8) for i,v in enumerate(pram)),64),(start,4),(length,4),(rop,2),(ead,18),(mask,16),(len(words),16),(len(changes),6)]
  value=0
  for v,width in fields:
   if not 0<=v<1<<width:raise ValueError('Overflow '+name)
   value=(value<<width)|v
  vectors.append((name,value));words.extend((off<<32)|(before<<16)|after for off,before,after in changes)
 if len(vectors)!=545 or len(unknown)!=9:raise ValueError('Accounting changed')
 out=['// Generated by tools/gen_gdc_character_vectors.py; no drawing algorithm.',
 '// Source554 complete INFO/OBS rows;545 explicit-input cases replayed.',
 '// Unreplayed missing glyph input bytes: '+', '.join(unknown),
 'localparam integer GCHR_CAPTURE_ROWS=554, GCHR_CASES=545, GCHR_UNREPLAYED=9;',
 "localparam logic [173:0] GCHR_VECTORS [0:GCHR_CASES-1] = '{"]
 out += [f"174'h{v:044X}"+(',' if i+1<len(vectors) else '')+' // '+n for i,(n,v) in enumerate(vectors)]
 out += ['};',f'localparam integer GCHR_WORDS={len(words)};',"localparam logic [45:0] GCHR_PIXELS [0:GCHR_WORDS-1] = '{"]
 out += [f"46'h{v:012X}"+(',' if i+1<len(words) else '') for i,v in enumerate(words)]
 return '\n'.join(out+['};',''])
if __name__=='__main__':
 s=render()
 if '--check' in sys.argv:
  if OUTPUT.read_text()!=s:raise SystemExit('FAIL regenerate GCHRD vectors')
  print('GDC character capture vectors: PASS (545 replayable;9 missing glyph bytes)')
 else:OUTPUT.write_text(s,newline='\n')
