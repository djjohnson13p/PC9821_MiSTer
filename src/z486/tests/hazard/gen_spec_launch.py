#!/usr/bin/env python3
"""Generates tests/programs/hz_spec_launch_rm.asm (see its header)."""
import os

KINDS = [
    # (id, preset imm16, store sequence) - each leaves imm16 = 0x2222 + N
    (1, "0x1111", ["mov [S + 1], bx"]),
    (2, "0x2221 + {n}", ["inc word [S + 1]"]),
    (3, "0x1111", ["add [S + 1], dx"]),
    (4, "0x1111", ["xchg [S + 1], bx"]),
    (5, "0x1122 + {n}", ["mov byte [S + 2], 0x22"]),
    (6, "0x1111", ["stosw"]),
    (7, "0x2211", ["mov dword [S - 2], 0x00b89090 | ((0x22 + {n}) << 24)"]),
]
FORMS = ["call", "jcc", "pre"]
FLAGS = {2, 3}  # INC and ADD write ZF (to 0): their not-taken branch is JZ

hdr = """; hz_spec_launch_rm - a store into a code line in the cycle the branch-target
; request for that line launches (or is pending, or is in flight)
;
; GENERATED by tests/hazard/gen_spec_launch.py - edit the generator.
;
; The prefetcher's branch-target buffer poisons an in-flight target fetch when a
; store hits its line (spec_kill). At launch the poison is seeded from spec_kill,
; which compares the store with the line being REPLACED, so each trial puts a
; store to S's line right before a branch whose target is S, with S's line warm
; in the I-cache and in neither branch-target slot. A 486 must run the patched
; code after the branch. Store kinds: MOV m16,r (1), INC m16 (2), ADD m16,r (3),
; XCHG m16,r (4), MOV m8,imm (5), STOSW (6), a dword store that crosses into S's
; line from the line before (7). Forms: CALL S directly (0); a not-taken Jcc S
; right after the store that buffers the line, then a CALL S that adopts it (1);
; S buffered by a not-taken JNE S just BEFORE the store, so the store must kill
; it in the cycle the CALL's flush may already be using it (2). Padding N = 0..7.
; Failure data = (form << 12) | (kind << 8) | N of the first failure.
BITS 16
ORG 0
start:
    cli
    xor ax, ax
    mov ss, ax
    mov sp, 0x8000
    mov ax, cs
    mov ds, ax
    mov es, ax
    cld
"""
body = []
t = 0
for fi, form in enumerate(FORMS):
    for kid, preset, seq in KINDS:
        for n in range(8):
            t += 1
            p = preset.format(n=n)
            body += [
                f"    ; form {fi} kind {kid} N {n}",
                "    mov word [S + 1], 0x1111",
                "    call S                         ; S's line warm in the I-cache",
                f"    jmp e1_{t}                      ; two new targets evict S from both slots",
                "    align 16",
                f"e1_{t}:",
                f"    jmp e2_{t}",
                "    align 16",
                f"e2_{t}:",
                f"    mov word [S + 1], {p}",
                f"    mov bx, 0x2222 + {n}",
                f"    mov ax, bx",
                f"    mov dx, 0x2222 + {n} - 0x1111",
                "    mov di, S + 1",
                "    cmp sp, sp                     ; ZF = 1",
            ]
            if form == "pre":
                body += ["    jne S                          ; not taken: S buffered before the store"]
            body += ["    " + s.format(n=n) for s in seq]
            body += ["    nop"] * n
            if form == "jcc":
                jcc = "jz" if kid in FLAGS else "jne"
                body += [f"    {jcc} S                           ; not taken: buffers S's line"]
            body += [
                "    call S",
                f"    cmp ax, 0x2222 + {n}",
                f"    je ok_{t}",
                f"    mov ax, ({fi} << 12) | ({kid} << 8) | {n}",
                "    jmp fail",
                f"ok_{t}:",
            ]
tail = """    mov al, 1
    out 0xe0, al
    hlt
fail:
    movzx eax, ax
    out 0xe4, eax
    mov al, 0xff
    out 0xe0, al
    hlt

    align 16
S:
    mov ax, 0x0000                   ; B8 iw: the imm16 at S + 1
    ret
"""
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "programs", "hz_spec_launch_rm.asm"), "w").write(
    hdr + "\n".join(body) + "\n" + tail)
